// --- i18n Engine ---
let currentLang = localStorage.getItem('yayika_lang') || 'es';

function t(key) {
  return (I18N[currentLang] && I18N[currentLang][key]) || I18N['es'][key] || key;
}

function setLanguage(lang) {
  currentLang = lang;
  localStorage.setItem('yayika_lang', lang);
  document.documentElement.lang = lang;
  applyTranslations();
  // Update dynamic elements
  if (typeof updateDate === 'function') updateDate();
  // Update lang selector active state
  document.querySelectorAll('.lang-opt').forEach(el => {
    el.classList.toggle('active', el.dataset.lang === lang);
  });
}

function applyTranslations() {
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.dataset.i18n;
    const translated = t(key);
    if (translated) el.textContent = translated;
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.dataset.i18nPlaceholder;
    const translated = t(key);
    if (translated) el.placeholder = translated;
  });
  // Update meta tags
  const metaDesc = document.querySelector('meta[name="description"]');
  if (metaDesc) {
    const descs = {
      es: 'Yayika — Productos digitales para mujeres: planners, guías y programas de bienestar, productividad y finanzas personales.',
      en: 'Yayika — Digital products for women: planners, guides and programs for wellness, productivity and personal finance.',
      pt: 'Yayika — Produtos digitais para mulheres: planners, guias e programas de bem-estar, produtividade e finanças pessoais.',
      fr: 'Yayika — Produits numériques pour femmes : planners, guides et programmes de bien-être, productivité et finances personnelles.',
      de: 'Yayika — Digitale Produkte für Frauen: Planer, Leitfäden und Programme für Wohlbefinden, Produktivität und persönliche Finanzen.'
    };
    metaDesc.content = descs[currentLang] || descs.es;
  }
  // Update JSON-LD
  const jsonLd = { 'es': 'es-MX', 'en': 'en-US', 'pt': 'pt-BR', 'fr': 'fr-FR', 'de': 'de-DE' };
  const ldScript = document.querySelector('script[type="application/ld+json"]');
  if (ldScript) {
    try {
      const ld = JSON.parse(ldScript.textContent);
      ld.inLanguage = jsonLd[currentLang] || 'es-MX';
      ldScript.textContent = JSON.stringify(ld, null, 2);
    } catch(e) {}
  }
  // Update prices
  updatePrices();
}

function updatePrices() {
  const sym = t('price_symbol');
  const perMonth = t('price_per_month');
  // Products
  document.querySelectorAll('[data-i18n-price]').forEach(el => {
    const key = el.dataset.i18nPrice;
    const val = t(key);
    if (val && val !== key) el.textContent = sym + val;
  });
  document.querySelectorAll('[data-i18n-price-original]').forEach(el => {
    const key = el.dataset.i18nPriceOriginal;
    const val = t(key);
    if (val && val !== key) el.textContent = sym + val;
  });
  // Per-month labels
  document.querySelectorAll('[data-i18n-price-month]').forEach(el => {
    el.textContent = perMonth;
  });
  // Full price strings (products with discount)
  document.querySelectorAll('[data-i18n-price-full]').forEach(el => {
    const originalKey = el.dataset.i18nPriceFull;
    const newKey = el.dataset.i18nPriceNew;
    const origVal = t(originalKey);
    const newVal = t(newKey);
    if (origVal && newVal) {
      el.innerHTML = '<s>' + sym + origVal + '</s> ' + sym + newVal + ' ' + t('price_currency');
    }
  });
  document.querySelectorAll('[data-i18n-price-simple]').forEach(el => {
    const key = el.dataset.i18nPriceSimple;
    const val = t(key);
    if (val) el.innerHTML = sym + val + ' ' + t('price_currency');
  });
  // Membership full price strings
  document.querySelectorAll('[data-i18n-plan-price]').forEach(el => {
    const key = el.dataset.i18nPlanPrice;
    const val = t(key);
    if (val) el.textContent = sym + val;
  });
  // Update JSON-LD currency (find the Product schema)
  document.querySelectorAll('script[type="application/ld+json"]').forEach(ldScript => {
    try {
      const ld = JSON.parse(ldScript.textContent);
      if (ld['@type'] === 'Product' && ld.offers) {
        ld.offers.priceCurrency = t('price_currency');
        ld.offers.price = t('price_ciclo');
        ldScript.textContent = JSON.stringify(ld, null, 2);
      }
    } catch(e) {}
  });
}
